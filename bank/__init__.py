"""bank —— 题库（数据模型 + 导入 + 查询）。

阶段2 的产物：把阶段1（``pipeline``）产出的结构化 JSON 落进 SQLite，并提供
导入（幂等）、检索（中文分词）、筛选、待复核队列、统计等能力，供阶段3（组卷）与
阶段4（导出）调用。

模块划分
--------
* ``textutil``  —— 占位符剥离、内容哈希、中文双字切分等文本工具
* ``metadata``  —— 从文件名/题干提取 学段/年级/教材版本/章节/学科/题型
* ``db``        —— SQLite schema、建库、连接、版本管理
* ``importer``  —— 把阶段1 的 JSON 导入数据库（幂等、可容错）
* ``enrich``    —— 元数据补全（保守推断 + provenance，含幂等迁移）
* ``labels``    —— 知识点人工复核工作流（review_status、确认/否决、CSV 导出导入）
* ``answers``   —— 答案 / 解析抽取（题干内联拆分 + 配对文件对齐）
* ``query``     —— 查询接口（筛选 / 关键词检索 / 分页 / 统计 / 待复核）
* ``paper``     —— 组卷（试卷/大题/条目数据模型、组卷操作、导出数据准备）
* ``export``    —— 导出（payload → DOCX（原生 OMML 公式）/ PDF，Word/WPS 双客户端可编辑性验证）
* ``cli``       —— 命令行入口 ``python -m bank.cli ...``
"""
