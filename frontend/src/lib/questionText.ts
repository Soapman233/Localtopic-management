/** 题干文本的**展示期**清洗（不改数据）。
 *
 * 背景（UI 评审 F4 / T05）
 * ----------------------
 * 部分来源文件把「答案」与「详解」直接写进了题干正文，例如
 * `GET /api/questions/3521` 的 `text`（296 字）实际是：
 *
 *   题干 + 选项 + `【答案】D` + `【详解】A．…故选D。`
 *
 * 而 `answer` 字段是 `D`、`analysis` 字段是**同一段详解**（188 字）。三处同源 →
 * 详情页会把同一份内容渲染三遍；检索结果卡也把 `【答案】D【详解】…` 整段铺在列表里。
 *
 * 处理原则
 * --------
 * 1. **只影响展示**：绝不修改 `text` 字段本身（编辑态仍按原文本编辑、后端不受影响）；
 * 2. **只认全角 `【】` + 固定词**：公式里可能出现半角方括号（`[` `]`）或其它中括号用法，
 *    宽泛匹配会误伤，故只匹配下列固定词；
 * 3. 命中即**截断**：这些标记之后的内容属于答案/解析区，由页面各自的「答案」「解析」区块
 *    负责展示（详情页）或本就无需展示（列表卡只给题干预览）。
 */

/**
 * 题干内嵌「答案 / 解析」区段的起始标记（**固定词白名单**）。
 *
 * ⚠️ 顺序：`参考答案` 必须排在 `答案` 前，否则 `【参考答案】` 不会被识别为整体。
 * ⚠️ 不要在这里加通配（如 `【.*】`）——那会把公式或其它合法方括号内容一起切掉。
 */
const ANSWER_SECTION_RE = /【(?:参考答案|答案|详解|解析|解答|分析|点评)】/

/**
 * 剥离题干中内嵌的「答案 / 详解 / 解析」区段，只保留「题干 + 选项」。
 *
 * - 未命中标记 → 原样返回（长题 / 图片 / 无答案 / 未知字形等 fixture 不受影响）；
 * - 命中 → 截断到标记之前，并去掉尾部空白与换行；
 * - 标记位于开头（截断后为空）时返回空串，由调用方决定降级文案（不伪造内容）。
 */
export function stripAnswerSections(text: string | null | undefined): string {
  const src = text ?? ''
  const match = ANSWER_SECTION_RE.exec(src)
  if (!match || match.index === undefined) return src
  return src.slice(0, match.index).replace(/\s+$/, '')
}
